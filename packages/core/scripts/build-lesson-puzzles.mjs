// Picks the practice puzzles for each lesson from the bundled Lichess puzzle
// database extract (CC0, https://database.lichess.org/#puzzles) and writes
// src/lessons/puzzles.ts. Run after changing LESSON_THEMES below or the bundled set:
//
//   node packages/core/scripts/build-lesson-puzzles.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gunzipSync } from 'node:zlib';

const here = dirname(fileURLToPath(import.meta.url));
const csv = join(here, '../../../apps/server/data/puzzles-lichess.csv.gz');
const out = join(here, '../src/lessons/puzzles.ts');

/** Lesson id -> [Lichess theme, lowest rating, highest rating, most moves in the line]. */
const LESSON_THEMES = {
  hanging: ['hangingPiece', 500, 1200, 4],
  fork: ['fork', 600, 1300, 4],
  pin: ['pin', 700, 1400, 4],
  skewer: ['skewer', 700, 1500, 4],
  discovered: ['discoveredAttack', 700, 1500, 4],
  doubleCheck: ['doubleCheck', 800, 1600, 4],
  mateInOne: ['mateIn1', 400, 1000, 2],
  backRank: ['backRankMate', 600, 1400, 4],
  smothered: ['smotheredMate', 900, 1700, 4],
  arabian: ['arabianMate', 800, 1600, 4],
  mateInTwo: ['mateIn2', 800, 1500, 4],
  promotion: ['promotion', 700, 1400, 4],
  opposition: ['pawnEndgame', 800, 1500, 6],
  rookEndgame: ['rookEndgame', 800, 1500, 4],
  openingPrinciples: ['opening', 600, 1300, 4],
};
const PER_LESSON = 3;

const rows = gunzipSync(readFileSync(csv)).toString('utf8').trim().split('\n').slice(1);
const puzzles = rows.map((line) => {
  const [id, fen, moves, rating, , popularity, plays, themes] = line.split(',');
  return { id, fen, moves: moves.split(' '), rating: +rating, popularity: +popularity, plays: +plays, themes: themes.split(' ') };
});

const used = new Set();
const picked = {};
for (const [lesson, [theme, lo, hi, maxMoves]] of Object.entries(LESSON_THEMES)) {
  const pool = puzzles
    .filter((p) => p.themes.includes(theme) && p.rating >= lo && p.rating <= hi && p.moves.length <= maxMoves && p.popularity >= 90 && p.plays >= 500 && !used.has(p.id))
    .sort((a, b) => a.rating - b.rating || a.id.localeCompare(b.id));
  if (pool.length < PER_LESSON) throw new Error(`Only ${pool.length} puzzles for ${lesson} (${theme})`);
  // Easy, medium, harder: spread across the rating range.
  const at = [0.1, 0.5, 0.9].map((q) => pool[Math.floor(q * (pool.length - 1))]);
  for (const p of at) used.add(p.id);
  picked[lesson] = at.map(({ id, fen, moves, rating, plays, themes }) => ({ id, fen, moves, rating, plays, themes }));
}

const body = Object.entries(picked)
  .map(([lesson, list]) => `  ${lesson}: [\n${list.map((p) => `    ${JSON.stringify(p)},`).join('\n')}\n  ],`)
  .join('\n');
writeFileSync(
  out,
  `// Generated by scripts/build-lesson-puzzles.mjs. Do not edit by hand.
// Practice puzzles from the Lichess puzzle database (CC0): https://database.lichess.org/#puzzles
import type { PuzzleDto } from '../puzzle';

export const LESSON_PUZZLES: Record<string, PuzzleDto[]> = {
${body}
};
`,
);
