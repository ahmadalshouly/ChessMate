// Works out the position each famous game is shown by in a list (its first
// key moment, else the final position) and writes src/immortals/thumbs.ts, so
// the Immortals page can draw its boards without replaying every score with
// chess.js when it opens. Run after adding or changing a game:
//
//   npx tsx packages/core/scripts/build-immortal-thumbs.ts
//
// test/immortals.test.ts fails if the file is out of date.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { IMMORTAL_GAMES, computeImmortalThumb } from '../src/immortals';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '../src/immortals/thumbs.ts');

const q = (v: string | null) => (v === null ? 'null' : `'${v}'`);
const rows = IMMORTAL_GAMES.map((g) => {
  const t = computeImmortalThumb(g);
  return `  ${q(g.id)}: { ply: ${t.ply}, fen: ${q(t.fen)}, last: ${q(t.last)}, check: ${q(t.check)}, orientation: ${q(t.orientation)} },`;
});

writeFileSync(
  out,
  `import type { ImmortalThumb } from './types';

/*
 * Generated by scripts/build-immortal-thumbs.ts: do not edit by hand.
 * The key position of every famous game, so lists can draw it instantly.
 */
export const IMMORTAL_THUMBS: Readonly<Record<string, ImmortalThumb>> = {
${rows.join('\n')}
};
`,
);
console.log(`wrote ${rows.length} thumbnails to ${out}`);
