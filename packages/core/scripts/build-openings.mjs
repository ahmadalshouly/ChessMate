// Regenerates src/openings-data.ts from the CC0 Lichess opening tables in data/*.tsv
// (https://github.com/lichess-org/chess-openings, public domain / CC0).
// Usage: node scripts/build-openings.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Chess } from 'chess.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const rows = [];
// Every position on the way to a named line is theory too (e.g. 4.Ba4 in the Ruy Lopez is
// not a named position itself but sits on dozens of named lines).
const book = new Set();
for (const f of ['a', 'b', 'c', 'd', 'e']) {
  const lines = readFileSync(join(root, 'data', `${f}.tsv`), 'utf8').split('\n').slice(1);
  for (const line of lines) {
    if (!line.trim()) continue;
    const [eco, name, pgn] = line.split('\t');
    const chess = new Chess();
    for (const tok of pgn.split(/\s+/)) {
      if (!tok || /^\d+\.+$/.test(tok)) continue;
      chess.move(tok);
      book.add(chess.fen().split(' ').slice(0, 4).join(' '));
    }
    // Position key: placement, side to move, castling, en passant (no move counters).
    const key = chess.fen().split(' ').slice(0, 4).join(' ');
    rows.push({ key, eco, name, ply: chess.history().length });
  }
}
// Several lines can reach the same position; keep the one reached in fewest moves,
// then the first listed, so names stay stable.
const best = new Map();
for (const r of rows) {
  const prev = best.get(r.key);
  if (!prev || r.ply < prev.ply) best.set(r.key, r);
}
const body = [...best.values()].map((r) => `${r.key}|${r.eco}|${r.name}`).join('\n');
const out = `// Generated by scripts/build-openings.mjs. Do not edit by hand.
// Source: lichess-org/chess-openings, released under CC0 (public domain).
// Format: one opening per line, "<fen without move counters>|<eco>|<name>".
export const OPENINGS_DATA = ${JSON.stringify(body)};
`;
writeFileSync(join(root, 'src', 'openings-data.ts'), out);
console.log(`${best.size} positions from ${rows.length} lines`);

// ---------- opening book (src/book-data.ts) ----------
// Stored as 32-bit FNV-1a hashes to keep the bundle small. Lookups only ever happen for
// positions one move away from a book position (the game leaves the book for good after
// its first non-book move), so we check every such position here and fail on a collision.
function fnv1a(str) {
  let h = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}
const keyOf = (fen) => fen.split(' ').slice(0, 4).join(' ');
const hashes = new Set([...book].map(fnv1a));
if (hashes.size !== book.size) throw new Error('Hash collision inside the book; switch to a wider hash');
let checked = 0;
for (const parent of [new Chess().fen(), ...[...book].map((k) => `${k} 0 1`)]) {
  const c = new Chess(parent);
  for (const m of c.moves({ verbose: true })) {
    c.move(m);
    const k = keyOf(c.fen());
    if (!book.has(k) && hashes.has(fnv1a(k))) throw new Error(`False book hit for ${k}; switch to a wider hash`);
    c.undo();
    checked++;
  }
}
const bookOut = `// Generated by scripts/build-openings.mjs. Do not edit by hand.
// Source: lichess-org/chess-openings, released under CC0 (public domain).
// Every position on a named opening line, as base-36 FNV-1a hashes of the FEN without move counters.
export const BOOK_DATA = ${JSON.stringify([...hashes].sort((a, b) => a - b).map((h) => h.toString(36)).join(' '))};
`;
writeFileSync(join(root, 'src', 'book-data.ts'), bookOut);
console.log(`${book.size} book positions, ${checked} neighbouring positions checked for collisions`);
