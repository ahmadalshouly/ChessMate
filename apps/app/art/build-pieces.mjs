#!/usr/bin/env node
/**
 * Builds the piece PNGs the app ships from the SVG sources in art/pieces.
 *
 *   node apps/app/art/build-pieces.mjs
 *
 * Needs Playwright with Chromium (not an app dependency; `npx playwright install chromium`
 * if you don't have it). Only needed when adding or changing a piece set: the PNGs and
 * src/features/board/pieceImages.ts are committed.
 *
 * Why PNG: several sets use CSS classes, gradients with xlink inheritance and filters that
 * react-native-svg doesn't render the same on every platform. Rasterising once in a real
 * browser makes every set look identical on iOS, Android and web, with no native module.
 *
 * The "glass" set is ChessMate's own restyle of the Classic (Chessnut) shapes and is
 * generated here from art/pieces/classic.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Buffer } from 'node:buffer';
import { createRequire } from 'node:module';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, 'pieces');
const OUT = join(here, '..', 'assets', 'pieces');
const MAP = join(here, '..', 'src', 'features', 'board', 'pieceImages.ts');
const PX = 192;
const PIECES = ['wK', 'wQ', 'wR', 'wB', 'wN', 'wP', 'bK', 'bQ', 'bR', 'bB', 'bN', 'bP'];

/** Sets whose PNGs get a soft drop shadow baked in. */
const SHADOW = { glass: 'drop-shadow(0 5px 6px rgba(0,0,0,0.38))' };

function glassFrom(svg, white) {
  const defs = white
    ? `<defs><linearGradient id="cmw" x1="0" y1="0" x2="0.35" y2="1"><stop offset="0" stop-color="#ffffff" stop-opacity="0.98"/><stop offset="0.48" stop-color="#eef1f5" stop-opacity="0.9"/><stop offset="1" stop-color="#b9c0cb" stop-opacity="0.92"/></linearGradient></defs>`
    : `<defs><linearGradient id="cmb" x1="0" y1="0" x2="0.35" y2="1"><stop offset="0" stop-color="#6a707c"/><stop offset="0.42" stop-color="#2a2d33"/><stop offset="1" stop-color="#060607"/></linearGradient></defs>`;
  let out = svg.replace(/ style="color-scheme:light only"/, '');
  if (white) {
    out = out.replaceAll('fill="#fff"', 'fill="url(#cmw)"').replaceAll('stroke="#000"', 'stroke="#121317"');
    out = out.replace(/<svg([^>]*)>/, `<svg$1 fill="#121317">${defs}`);
  } else {
    out = out.replaceAll('stroke="#f2f2f2"', 'stroke="#ffffff" stroke-opacity="0.82"').replaceAll('fill="#f2f2f2"', 'fill="#ffffff" fill-opacity="0.82"');
    // A faint light rim keeps black glass pieces readable on dark squares.
    out = out.replace(/<svg([^>]*)>/, `<svg$1 fill="url(#cmb)" stroke="#ffffff" stroke-opacity="0.38" stroke-width="9">${defs}`);
  }
  return out;
}

function sources() {
  const sets = readdirSync(SRC, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name);
  const all = {};
  for (const set of sets) {
    all[set] = {};
    for (const p of PIECES) {
      const file = join(SRC, set, `${p}.svg`);
      if (existsSync(file)) all[set][p] = readFileSync(file, 'utf8');
      else if (set === 'glass') all[set][p] = glassFrom(readFileSync(join(SRC, 'classic', `${p}.svg`), 'utf8'), p[0] === 'w');
      else throw new Error(`Missing ${file}`);
    }
  }
  return all;
}

const { chromium } = createRequire(import.meta.url)('playwright');
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: PX, height: PX }, deviceScaleFactor: 1 });
const all = sources();
for (const [set, pieces] of Object.entries(all)) {
  mkdirSync(join(OUT, set), { recursive: true });
  for (const [p, svg] of Object.entries(pieces)) {
    const pad = SHADOW[set] ? 6 : 0;
    const html = `<!doctype html><html><body style="margin:0;background:transparent">
      <img src="data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}"
        style="display:block;width:${PX - pad * 2}px;height:${PX - pad * 2}px;margin:${pad / 2}px ${pad}px ${pad * 1.5}px;${SHADOW[set] ? `filter:${SHADOW[set]}` : ''}"></body></html>`;
    await page.setContent(html);
    await page.waitForFunction(() => document.images[0]?.complete);
    await page.screenshot({ path: join(OUT, set, `${p}.png`), omitBackground: true, clip: { x: 0, y: 0, width: PX, height: PX } });
  }
}
await browser.close();

const sets = Object.keys(all).sort();
const lines = [
  '// Generated by art/build-pieces.mjs. Do not edit by hand.',
  "import type { ImageSourcePropType } from 'react-native';",
  '',
  'export type PieceCode = ' + PIECES.map((p) => `'${p}'`).join(' | ') + ';',
  '',
  'export const PIECE_IMAGES: Record<string, Record<PieceCode, ImageSourcePropType>> = {',
  ...sets.map((set) => `  ${/^[a-z]+$/.test(set) ? set : `'${set}'`}: {\n${PIECES.map((p) => `    ${p}: require('../../../assets/pieces/${set}/${p}.png'),`).join('\n')}\n  },`),
  '};',
  '',
];
writeFileSync(MAP, lines.join('\n'));
console.log(`Built ${sets.length} sets x ${PIECES.length} pieces into ${OUT}`);
